// No social media on purpose: blank devices keep the tower spinning, screens use the default textures.
export const CONTENT_DATA = ['youtube', 'blog', 'tiktok'].flatMap((platform) =>
    [1, 2, 3, 4].map((n) => ({ id: `${platform}-${n}`, platform, date: '2026-01-01' }))
);

// Helper to get content by platform
export const getContentByPlatform = (platform) => {
    if (platform === 'all') return CONTENT_DATA;
    return CONTENT_DATA.filter(item => item.platform === platform);
};

// Get latest content (for "On Air" indicator)
export const getLatestContent = () => {
    return [...CONTENT_DATA].sort((a, b) => new Date(b.date) - new Date(a.date))[0];
};
